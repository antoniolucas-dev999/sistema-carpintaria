CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    ativo BOOLEAN
);


CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_razao_social VARCHAR(150) NOT NULL,
    cpf_cnpj VARCHAR(20) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    email VARCHAR(150),
    endereco VARCHAR(200),
    cidade VARCHAR(100),
    cep VARCHAR(10),
    observacoes VARCHAR(500)
);


CREATE TABLE orcamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    numero VARCHAR(30) UNIQUE,

    cliente_id BIGINT NOT NULL,
    vendedor_id BIGINT NOT NULL,

    data_emissao DATE NOT NULL,

    obra VARCHAR(150),
    tipo_madeira VARCHAR(100),
    observacoes VARCHAR(1000),

    subtotal NUMERIC(12,2) NOT NULL,

    percentual_frete NUMERIC(5,2),
    valor_frete NUMERIC(12,2),

    percentual_desconto NUMERIC(5,2),
    valor_desconto NUMERIC(12,2),

    total NUMERIC(12,2) NOT NULL,

    status VARCHAR(30) NOT NULL,

    CONSTRAINT ck_orcamentos_status
        CHECK (
            status IN (
                'RASCUNHO',
                'EMITIDO',
                'APROVADO',
                'REPROVADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT fk_orcamentos_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(id),

    CONSTRAINT fk_orcamentos_vendedor
        FOREIGN KEY (vendedor_id)
        REFERENCES usuarios(id)
);


CREATE TABLE orcamento_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    orcamento_id BIGINT NOT NULL,

    produto VARCHAR(200) NOT NULL,

    divisoria VARCHAR(100),
    ambiente VARCHAR(100),
    acionamento VARCHAR(100),

    criterio_venda VARCHAR(10) NOT NULL,

    quantidade INTEGER NOT NULL,

    comprimento NUMERIC(12,4),
    largura NUMERIC(12,4),
    espessura NUMERIC(12,4),

    medida_calculada NUMERIC(14,6) NOT NULL,

    preco_unitario NUMERIC(12,2) NOT NULL,
    valor_total NUMERIC(12,2) NOT NULL,

    CONSTRAINT ck_orcamento_itens_criterio_venda
        CHECK (
            criterio_venda IN (
                'ML',
                'M2',
                'M3'
            )
        ),

    CONSTRAINT fk_orcamento_itens_orcamento
        FOREIGN KEY (orcamento_id)
        REFERENCES orcamentos(id)
);