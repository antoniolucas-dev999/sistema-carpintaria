CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    numero VARCHAR(30) UNIQUE,

    cliente_id BIGINT NOT NULL,
    vendedor_id BIGINT NOT NULL,
    orcamento_id BIGINT,

    data_pedido DATE NOT NULL DEFAULT CURRENT_DATE,

    obra VARCHAR(150),
    observacoes VARCHAR(1000),

    status VARCHAR(40) NOT NULL DEFAULT 'RASCUNHO',

    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_pedidos_status
        CHECK (
            status IN (
                'RASCUNHO',
                'AGUARDANDO_FINANCEIRO',
                'FINANCEIRO_LIBERADO',
                'FINANCEIRO_REPROVADO',
                'EM_ANALISE_TECNICA',
                'PENDENCIA_TECNICA',
                'LIBERADO_PRODUCAO',
                'EM_PRODUCAO',
                'PRODUCAO_PARCIAL',
                'PRODUCAO_CONCLUIDA',
                'ENTREGA_PARCIAL',
                'ENTREGUE',
                'FINALIZADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT fk_pedidos_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(id),

    CONSTRAINT fk_pedidos_vendedor
        FOREIGN KEY (vendedor_id)
        REFERENCES usuarios(id),

    CONSTRAINT fk_pedidos_orcamento
        FOREIGN KEY (orcamento_id)
        REFERENCES orcamentos(id)
);


CREATE TABLE pedido_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pedido_id BIGINT NOT NULL,

    produto VARCHAR(200) NOT NULL,
    descricao VARCHAR(500),

    divisoria VARCHAR(100),
    ambiente VARCHAR(100),
    acionamento VARCHAR(100),

    unidade_medida VARCHAR(20) NOT NULL,

    quantidade_pedida NUMERIC(14,4) NOT NULL,

    percentual_tolerancia NUMERIC(5,2) NOT NULL DEFAULT 10.00,

    comprimento NUMERIC(12,4),
    largura NUMERIC(12,4),
    espessura NUMERIC(12,4),

    observacoes VARCHAR(500),

    CONSTRAINT ck_pedido_itens_quantidade
        CHECK (quantidade_pedida > 0),

    CONSTRAINT ck_pedido_itens_tolerancia
        CHECK (
            percentual_tolerancia >= 0
            AND percentual_tolerancia <= 10
        ),

    CONSTRAINT ck_pedido_itens_unidade
        CHECK (
            unidade_medida IN (
                'M2',
                'ML',
                'M3',
                'UN',
                'PC',
                'CJ'
            )
        ),

    CONSTRAINT fk_pedido_itens_pedido
        FOREIGN KEY (pedido_id)
        REFERENCES pedidos(id)
);


CREATE INDEX idx_pedidos_cliente
    ON pedidos(cliente_id);

CREATE INDEX idx_pedidos_vendedor
    ON pedidos(vendedor_id);

CREATE INDEX idx_pedidos_status
    ON pedidos(status);

CREATE INDEX idx_pedido_itens_pedido
    ON pedido_itens(pedido_id);